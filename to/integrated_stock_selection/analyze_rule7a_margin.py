import json
from pathlib import Path

import numpy as np
import pandas as pd


BASE = Path(__file__).resolve().parent
RESULTS = BASE / "results"
FACTOR_FILE = BASE / "factor_lab_data" / "factors.parquet"
RUN_FILES = {
    "old162_off": RESULTS / "walkforward_metrics_20260512_194610.json",
    "latest184_v3": RESULTS / "walkforward_metrics_20260520_190404.json",
    "latest185_off": RESULTS / "walkforward_metrics_20260520_210454.json",
}
FACTORS = ["top10_10d_strength_level_v3", "buy_sm_amount_rate"]


def load_events():
    rows = []
    for ds, path in RUN_FILES.items():
        data = json.loads(path.read_text(encoding="utf-8"))
        for t in data[0]["all_results"]["1"]["trades"]:
            rows.append(
                {
                    "dataset": ds,
                    "stock_code": t["stock_code"],
                    "buy_date": pd.Timestamp(t["buy_datetime"][:10]),
                    "actual_return": float(t["actual_return"]),
                    "profit_loss": float(t["profit_loss"]),
                }
            )
    events = pd.DataFrame(rows)
    events["key"] = events["stock_code"] + "|" + events["buy_date"].dt.strftime("%Y-%m-%d")
    return events


def enrich(events):
    df = pd.read_parquet(FACTOR_FILE, columns=["date", "stock_code"] + FACTORS)
    df["date"] = pd.to_datetime(df["date"])
    df = df.sort_values(["stock_code", "date"])
    grouped = {
        stock: (g["date"].to_numpy(dtype="datetime64[ns]"), g.reset_index(drop=True))
        for stock, g in df.groupby("stock_code", sort=False)
    }
    rows = []
    for _, e in events.iterrows():
        rec = e.to_dict()
        item = grouped.get(e["stock_code"])
        if item is not None:
            dates, g = item
            pos = np.searchsorted(dates, np.datetime64(e["buy_date"]), side="left") - 1
            if pos >= 0:
                r = g.iloc[int(pos)]
                rec["factor_date"] = r["date"]
                for c in FACTORS:
                    rec[c] = r[c]
        rows.append(rec)
    return pd.DataFrame(rows)


def current_v3_mask_full(events):
    # Use the richer file generated by the previous full scan if available;
    # otherwise return False for this focused margin analysis.
    return pd.Series(False, index=events.index)


def make_ref(df):
    priority = {"latest185_off": 0, "old162_off": 1, "latest184_v3": 2}
    x = df.copy()
    x["priority"] = x["dataset"].map(priority)
    return x.sort_values(["key", "priority"]).drop_duplicates("key", keep="first").drop(columns=["priority"])


def summarize(mask, frame):
    h = frame[mask]
    return {
        "n": int(len(h)),
        "loss": int((h["actual_return"] <= -0.05).sum()),
        "bigwin": int((h["actual_return"] >= 0.10).sum()),
        "pos": int((h["actual_return"] > 0).sum()),
        "avg": float(h["actual_return"].mean()) if len(h) else 0.0,
        "pnl": float(h["profit_loss"].sum()) if len(h) else 0.0,
    }


def main():
    df = enrich(load_events())
    ref = make_ref(df)
    recent = df[
        df["dataset"].eq("latest184_v3")
        & (df["buy_date"] >= pd.Timestamp("2026-04-01"))
        & (df["actual_return"] <= -0.05)
    ].copy()
    hist = ref[~ref["key"].isin(recent["key"])].copy()
    wins = hist[hist["actual_return"] >= 0.10]
    losses = hist[hist["actual_return"] <= -0.05]
    neutral = hist[(hist["actual_return"] > -0.05) & (hist["actual_return"] < 0.10)]

    print("== Rule7a margin grid ==")
    print(f"recent_losses={len(recent)}, hist_bigwins={len(wins)}, hist_bigloss={len(losses)}, neutral={len(neutral)}")
    all_ref = hist
    for c in FACTORS:
        print(
            "{} percentiles: p10={:.3f}, p15={:.3f}, p20={:.3f}, p25={:.3f}, p50={:.3f}, p70={:.3f}, p75={:.3f}, p80={:.3f}".format(
                c,
                all_ref[c].quantile(0.10),
                all_ref[c].quantile(0.15),
                all_ref[c].quantile(0.20),
                all_ref[c].quantile(0.25),
                all_ref[c].quantile(0.50),
                all_ref[c].quantile(0.70),
                all_ref[c].quantile(0.75),
                all_ref[c].quantile(0.80),
            )
        )

    strength_grid = [0.60, 0.65, 0.70, 0.75, 0.80]
    sm_grid = [-0.75, -1.00, -1.25, -1.50, -2.00]
    rows = []
    for st in strength_grid:
        for sm in sm_grid:
            def m(x):
                return (x["top10_10d_strength_level_v3"] >= st) & (x["buy_sm_amount_rate"] <= sm)

            sr = summarize(m(recent), recent)
            sw = summarize(m(wins), wins)
            sl = summarize(m(losses), losses)
            sn = summarize(m(neutral), neutral)
            score = sr["n"] * 10 + sl["n"] * 1.5 - sw["n"] * 8 - sn["n"] * 0.8
            rows.append(
                {
                    "strength_th": st,
                    "buy_sm_th": sm,
                    "strength_pct_leq": float((all_ref["top10_10d_strength_level_v3"] <= st).mean()),
                    "buy_sm_pct_leq": float((all_ref["buy_sm_amount_rate"] <= sm).mean()),
                    "recent_hit": sr["n"],
                    "hist_bigwin_hit": sw["n"],
                    "hist_bigloss_hit": sl["n"],
                    "neutral_hit": sn["n"],
                    "score": score,
                }
            )

    out = pd.DataFrame(rows).sort_values(
        ["score", "recent_hit", "hist_bigwin_hit", "neutral_hit"],
        ascending=[False, False, True, True],
    )
    out.to_csv(RESULTS / "rule7a_margin_grid.csv", index=False, encoding="utf-8-sig")
    print(out.to_string(index=False, float_format=lambda x: f"{x:.3f}"))

    print("\n== Hit details for recommended rounded candidates ==")
    candidates = [(0.65, -1.0), (0.70, -1.0), (0.70, -1.25), (0.75, -1.0)]
    for st, sm in candidates:
        mask = (df["top10_10d_strength_level_v3"] >= st) & (df["buy_sm_amount_rate"] <= sm)
        print(f"\nRule7a rounded: strength>={st:.2f} & buy_sm_amount_rate<={sm:.2f}")
        for ds in sorted(df["dataset"].unique()):
            d = df[df["dataset"].eq(ds)]
            s = summarize(mask.loc[d.index], d)
            print(
                f"  {ds}: n={s['n']} loss={s['loss']} bigwin={s['bigwin']} pos={s['pos']} avg={s['avg']:.2%} pnl={s['pnl']:.0f}"
            )
        h = df[mask].sort_values(["actual_return", "buy_date"])
        for _, r in h.head(16).iterrows():
            print(
                "    {ds} {date} {code} ret={ret:.2%} strength={stg:.3f} buy_sm={bsm:.3f}".format(
                    ds=r["dataset"],
                    date=r["buy_date"].date(),
                    code=r["stock_code"],
                    ret=r["actual_return"],
                    stg=r["top10_10d_strength_level_v3"],
                    bsm=r["buy_sm_amount_rate"],
                )
            )


if __name__ == "__main__":
    main()
